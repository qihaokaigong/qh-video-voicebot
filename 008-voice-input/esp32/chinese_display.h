inline uint32_t nextCodePoint(const char *&cursor) {
  const auto first = static_cast<uint8_t>(*cursor++);
  if (first < 0x80) return first;
  if ((first & 0xe0) == 0xc0) {
    const auto second = static_cast<uint8_t>(*cursor++);
    return ((first & 0x1f) << 6) | (second & 0x3f);
  }
  if ((first & 0xf0) == 0xe0) {
    const auto second = static_cast<uint8_t>(*cursor++);
    const auto third = static_cast<uint8_t>(*cursor++);
    return ((first & 0x0f) << 12) | ((second & 0x3f) << 6) |
           (third & 0x3f);
  }
  return 0;
}

inline const Glyph *findGlyph(uint32_t codepoint) {
  for (const auto &glyph : kGlyphs) {
    if (glyph.codepoint == codepoint) return &glyph;
  }
  return nullptr;
}

inline bool hasCompleteGlyphCoverage(const char *text) {
  const char *cursor = text;
  while (*cursor) {
    const uint32_t codepoint = nextCodePoint(cursor);
    if (codepoint != ' ' && findGlyph(codepoint) == nullptr) return false;
  }
  return true;
}

inline int16_t textWidth(const char *text, uint8_t scale) {
  const char *cursor = text;
  int16_t width = 0;
  bool first = true;
  while (*cursor) {
    const uint32_t codepoint = nextCodePoint(cursor);
    const int16_t glyph_width = codepoint == ' ' ? 8 : 16;
    if (!first) width += static_cast<int16_t>(2 * scale);
    width += static_cast<int16_t>(glyph_width * scale);
    first = false;
  }
  return width;
}

template <typename Canvas>
void drawText(Canvas &canvas, const char *text, int16_t x, int16_t y,
              uint16_t color, uint8_t scale) {
  const char *cursor = text;
  canvas.startWrite();
  while (*cursor) {
    const uint32_t codepoint = nextCodePoint(cursor);
    if (codepoint == ' ') {
      x += static_cast<int16_t>(10 * scale);
      continue;
    }
    const Glyph *glyph = findGlyph(codepoint);
    if (glyph == nullptr) continue;
    for (int16_t row = 0; row < 16; ++row) {
      for (int16_t column = 0; column < 16; ++column) {
        if ((glyph->rows[row] & (1U << (15 - column))) != 0) {
          canvas.writeFillRect(x + column * scale, y + row * scale, scale,
                               scale, color);
        }
      }
    }
    x += static_cast<int16_t>(18 * scale);
  }
  canvas.endWrite();
}

template <typename Canvas>
void drawCentered(Canvas &canvas, const char *text, int16_t canvas_width,
                  int16_t y, uint16_t color, uint8_t scale) {
  const int16_t width = textWidth(text, scale);
  drawText(canvas, text, static_cast<int16_t>((canvas_width - width) / 2), y,
           color, scale);
}

